end

function make_table_rows(systems::AbstractVector{HSKLSystemSpec}, profiles::AbstractDict, objects::AbstractVector{<:AbstractDict})
    system_rows = Dict{String,Any}[]
    regime_rows = Dict{String,Any}[]
    split_rows = Dict{String,Any}[]
    window_rows = Dict{String,Any}[]
    validation_rows = Dict{String,Any}[]

    for system in systems
        push!(
            system_rows,
            Dict(
                "system_id" => system.system_id,
                "layer" => system.layer,
                "d_x" => system.state_dim,
                "available_difficulty_levels" => join(sort(collect(keys(profiles))), "|"),
                "available_parameter_regimes" => join([regime["parameter_regime"] for regime in system.regimes], "|"),
                "available_splits" => "split_i_initial_condition|split_p_parameter",
            ),
        )
        for (idx, regime) in enumerate(system.regimes)
            params = Dict(k => v for (k, v) in regime if k != "parameter_regime")
            push!(
                regime_rows,
                Dict(
                    "benchmark_version" => HSKL_BENCHMARK_VERSION,
                    "system_id" => system.system_id,
                    "parameter_regime" => regime["parameter_regime"],
                    "split_p_role" => split_p_role(idx, length(system.regimes)),
                    "parameters_json" => JSON.json(params),
                ),
            )
        end
    end

    for object in objects
        counts = object["split_counts"]
        feasibility = object["window_feasibility"]
        validation = object["validation"]
        push!(
            split_rows,
            Dict(
                "system_id" => object["system_id"],
                "difficulty_level" => object["difficulty_level"],
                "parameter_regime" => object["parameter_regime"],
                "split_id" => object["split_id"],
                "R_train" => counts["train"],
                "R_val" => counts["val"],
                "R_test" => counts["test"],
                "trajectory_id_overlap_count" => 0,
            ),
        )
        push!(
            window_rows,
            Dict(
                "system_id" => object["system_id"],
                "difficulty_level" => object["difficulty_level"],
                "M" => object["M"],
                "L_H" => join(profiles[object["difficulty_level"]]["L_H"], "|"),
                "L_rec" => join(profiles[object["difficulty_level"]]["L_rec"], "|"),
                "L_roll" => join(profiles[object["difficulty_level"]]["L_roll"], "|"),
                "S_H" => feasibility["S_H_min"],
                "S_rec" => feasibility["S_rec_min"],
                "S_roll" => feasibility["S_roll_min"],
                "window_feasible" => feasibility["window_feasible"],
            ),
        )
        push!(
            validation_rows,
            Dict(
                "system_id" => object["system_id"],
                "difficulty_level" => object["difficulty_level"],
                "split_id" => object["split_id"],
                "parameter_regime" => object["parameter_regime"],
                "finite_check" => validation["finite_check"],
                "shape_check" => validation["shape_check"],
                "full_state_check" => validation["full_state_check"],
                "clean_noise_check" => validation["clean_noise_check"],
                "split_check" => validation["split_check"],
                "window_check" => validation["window_check"],
                "status" => validation["status"],
            ),
        )
    end
    return system_rows, regime_rows, split_rows, window_rows, validation_rows
end

function failure_counters(objects::AbstractVector{<:AbstractDict})
    counters = Dict(
        "nonfinite_count" => 0,
        "shape_mismatch_count" => 0,
        "split_overlap_count" => 0,
        "full_state_violation_count" => 0,
        "noise_violation_count" => 0,
        "window_infeasible_count" => 0,
        "empty_trajectory_count" => 0,
        "constant_trajectory_count" => 0,
        "metadata_missing_count" => 0,
    )
    for object in objects
        validation = object["validation"]
        validation["finite_check"] || (counters["nonfinite_count"] += 1)
        validation["shape_check"] || (counters["shape_mismatch_count"] += 1)
        validation["split_check"] || (counters["split_overlap_count"] += 1)
        validation["full_state_check"] || (counters["full_state_violation_count"] += 1)
        validation["clean_noise_check"] || (counters["noise_violation_count"] += 1)
        validation["window_check"] || (counters["window_infeasible_count"] += 1)
        validation["nonconstant_check"] || (counters["constant_trajectory_count"] += 1)
    end
    return counters
end

