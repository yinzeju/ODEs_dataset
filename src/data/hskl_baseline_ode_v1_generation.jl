function yaml_scalar(value)
    if value isa AbstractString
        return string('"', replace(value, "\"" => "\\\""), '"')
    elseif value isa AbstractVector
        return string("[", join(yaml_scalar.(value), ", "), "]")
    else
        return string(value)
    end
end

