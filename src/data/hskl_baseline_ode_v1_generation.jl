## System equations and RK4 integration

function hskl_rhs!(dx::AbstractVector{Float64}, system_id::AbstractString, x::AbstractVector{Float64}, params::AbstractDict)
    if system_id == "linear_diagonal"
        eigenvalues = Float64.(params["eigenvalues"])
        @inbounds for i in eachindex(dx)
            dx[i] = eigenvalues[i] * x[i]
        end
    elseif system_id == "linear_rotation_contraction"
        sigma = Float64(params["sigma"])
        omega = Float64(params["omega"])
        @inbounds for block in 1:(length(x) ÷ 2)
            i = 2 * block - 1
            dx[i] = sigma * x[i] - omega * x[i + 1]
            dx[i + 1] = omega * x[i] + sigma * x[i + 1]
        end
    elseif system_id == "linear_jordan_nonnormal"
        alpha = Float64(params["alpha"])
        eta = Float64(params["eta"])
        dx[1] = alpha * x[1] + eta * x[2]
        dx[2] = alpha * x[2]
    elseif system_id == "damped_linear_oscillator"
        beta = Float64(params["beta"])
        omega = Float64(params["omega"])
        dx[1] = x[2]
        dx[2] = -2.0 * beta * x[2] - omega^2 * x[1]
    elseif system_id == "van_der_pol"
        mu = Float64(params["mu"])
        dx[1] = x[2]
        dx[2] = mu * (1.0 - x[1]^2) * x[2] - x[1]
    elseif system_id == "duffing"
        delta = Float64(params["delta"])
        alpha = Float64(params["alpha"])
        beta = Float64(params["beta"])
        dx[1] = x[2]
        dx[2] = -delta * x[2] - alpha * x[1] - beta * x[1]^3
    elseif system_id == "lotka_volterra"
        a = Float64(params["a"])
        b = Float64(params["b"])
        c = Float64(params["c"])
        d = Float64(params["d"])
        dx[1] = a * x[1] - b * x[1] * x[2]
        dx[2] = -c * x[2] + d * x[1] * x[2]
    elseif system_id == "fitzhugh_nagumo"
        a = Float64(params["a"])
        b = Float64(params["b"])
        epsilon = Float64(params["epsilon"])
        current = Float64(params["I"])
        dx[1] = x[1] - x[1]^3 / 3.0 - x[2] + current
        dx[2] = epsilon * (x[1] + a - b * x[2])
    elseif system_id == "lorenz63"
        sigma = Float64(params["sigma"])
        rho = Float64(params["rho"])
        beta = Float64(params["beta"])
        dx[1] = sigma * (x[2] - x[1])
        dx[2] = x[1] * (rho - x[3]) - x[2]
        dx[3] = x[1] * x[2] - beta * x[3]
    elseif system_id == "rossler"
        a = Float64(params["a"])
        b = Float64(params["b"])
        c = Float64(params["c"])
        dx[1] = -x[2] - x[3]
        dx[2] = x[1] + a * x[2]
        dx[3] = b + x[3] * (x[1] - c)
    elseif system_id == "lorenz96"
        forcing = Float64(params["F"])
        n = length(x)
        @inbounds for i in 1:n
            im2 = mod1(i - 2, n)
            im1 = mod1(i - 1, n)
            ip1 = mod1(i + 1, n)
            dx[i] = (x[ip1] - x[im2]) * x[im1] - x[i] + forcing
        end
    else
        throw(ArgumentError("unknown HSKL system_id: $(system_id)"))
    end
    return dx
end

function rk4_step!(out::AbstractVector{Float64}, system_id::AbstractString, x::AbstractVector{Float64}, params::AbstractDict, dt::Real)
    k1 = similar(x)
    k2 = similar(x)
    k3 = similar(x)
    k4 = similar(x)
    temp = similar(x)
    h = Float64(dt)

    hskl_rhs!(k1, system_id, x, params)
    @. temp = x + 0.5 * h * k1
    hskl_rhs!(k2, system_id, temp, params)
    @. temp = x + 0.5 * h * k2
    hskl_rhs!(k3, system_id, temp, params)
    @. temp = x + h * k3
    hskl_rhs!(k4, system_id, temp, params)
    @. out = x + h * (k1 + 2.0 * k2 + 2.0 * k3 + k4) / 6.0
    return out
end

function advance_state(system::HSKLSystemSpec, params::AbstractDict, x0::AbstractVector{<:Real}, steps::Integer)
    x = Float64.(x0)
    next_x = similar(x)
    for _ in 1:steps
        rk4_step!(next_x, system.system_id, x, params, system.dt)
        x, next_x = next_x, x
    end
    return copy(x)
end

function generate_state_matrix(system::HSKLSystemSpec, params::AbstractDict, x0::AbstractVector{<:Real}, M::Integer)
    burn_steps = Int(round(system.burn_in_time / system.dt))
    x = advance_state(system, params, x0, burn_steps)
    X = Matrix{Float64}(undef, system.state_dim, M + 1)
    X[:, 1] = x
    next_x = similar(x)
    @inbounds for m in 1:M
        rk4_step!(next_x, system.system_id, x, params, system.dt)
        X[:, m + 1] = next_x
        x, next_x = next_x, x
    end
    return X
end

## Initial-condition protocol

function sample_box_min_abs(rng::AbstractRNG, state_dim::Integer; lower::Real = -1.0, upper::Real = 1.0, min_abs::Real = 0.05)
    for _ in 1:10_000
        x0 = lower .+ (upper - lower) .* rand(rng, state_dim)
        minimum(abs.(x0)) >= min_abs && return Vector{Float64}(x0)
    end
    throw(ArgumentError("failed to sample nontrivial box initial condition"))
end

function sample_initial_condition(rng::AbstractRNG, system::HSKLSystemSpec, params::AbstractDict)
    if system.initial_condition_domain == "box_min_abs"
        return sample_box_min_abs(rng, system.state_dim)
    elseif system.initial_condition_domain == "repeated_polar_annulus"
        x0 = Vector{Float64}(undef, system.state_dim)
        for block in 1:(system.state_dim ÷ 2)
            radius = 0.5 + 1.5 * rand(rng)
            angle = 2.0 * pi * rand(rng)
            i = 2 * block - 1
            x0[i] = radius * cos(angle)
            x0[i + 1] = radius * sin(angle)
        end
        return x0
    elseif system.initial_condition_domain == "oscillator_box"
        return [-2.0 + 4.0 * rand(rng), -1.5 + 3.0 * rand(rng)]
    elseif system.initial_condition_domain == "wide_box"
        return -2.5 .+ 5.0 .* rand(rng, system.state_dim)
    elseif system.initial_condition_domain == "positive_orbit_family"
        a = Float64(params["a"])
        b = Float64(params["b"])
        c = Float64(params["c"])
        d = Float64(params["d"])
        equilibrium = [c / d, a / b]
        scales = 0.55 .+ 1.35 .* rand(rng, 2)
        return equilibrium .* scales
    elseif system.initial_condition_domain == "fitzhugh_box"
        return [-2.0 + 4.0 * rand(rng), -0.5 + 2.0 * rand(rng)]
    elseif system.initial_condition_domain == "lorenz63_box"
        return [-10.0 + 20.0 * rand(rng), -10.0 + 20.0 * rand(rng), 5.0 + 30.0 * rand(rng)]
    elseif system.initial_condition_domain == "rossler_box"
        return [-8.0 + 16.0 * rand(rng), -8.0 + 16.0 * rand(rng), 0.1 + 7.9 * rand(rng)]
    elseif system.initial_condition_domain == "lorenz96_perturbed_equilibrium"
        forcing = Float64(params["F"])
        return forcing .+ 0.25 .* randn(rng, system.state_dim)
    else
        throw(ArgumentError("unknown initial condition domain: $(system.initial_condition_domain)"))
    end
end

function deterministic_seed(parts...)
    total = UInt64(0)
    for part in parts
        for byte in codeunits(string(part))
            total = total * UInt64(131) + UInt64(byte)
        end
    end
    return Int(mod(total, UInt64(2_000_000_000))) + 1
end

## Split, tensor, and validation helpers

function trajectory_roles(profile::AbstractDict)
    roles = String[]
    append!(roles, fill("train", Int(profile["R_train"])))
    append!(roles, fill("val", Int(profile["R_val"])))
    append!(roles, fill("test", Int(profile["R_test"])))
    return roles
end

function trajectory_tensor(matrices::AbstractVector{<:AbstractMatrix})
    first_matrix = first(matrices)
    tensor = Array{Float64}(undef, size(first_matrix, 1), size(first_matrix, 2), length(matrices))
    for (q, matrix) in enumerate(matrices)
        tensor[:, :, q] = matrix
    end
    return tensor
end

function window_feasibility(profile::AbstractDict)
    M = Int(profile["M"])
    L_H_values = Int.(profile["L_H"])
    L_rec_values = Int.(profile["L_rec"])
    L_roll_values = Int.(profile["L_roll"])
    S_H_min = minimum(M .- L_H_values .+ 1)
    S_rec_min = minimum(M .- L_rec_values .+ 1)
    S_roll_min = minimum(M .- L_roll_values .+ 1)
    return Dict(
        "S_H_min" => S_H_min,
        "S_rec_min" => S_rec_min,
        "S_roll_min" => S_roll_min,
        "window_feasible" => S_H_min > 0 && S_rec_min > 0 && S_roll_min > 0,
    )
end

function validate_release_object(X::Array{Float64,3}, Z::Array{Float64,3}, Y::Array{Float64,3}, profile::AbstractDict, roles::AbstractVector{String})
    shape_check = size(X) == size(Z) == size(Y)
    finite_check = all(isfinite, X) && all(isfinite, Z) && all(isfinite, Y)
    full_state_check = maximum(abs.(Z .- X)) == 0.0 && maximum(abs.(Y .- X)) == 0.0
    clean_noise_check = full_state_check
    split_check = count(==("train"), roles) == Int(profile["R_train"]) &&
        count(==("val"), roles) == Int(profile["R_val"]) &&
        count(==("test"), roles) == Int(profile["R_test"])
    window_check = Bool(window_feasibility(profile)["window_feasible"])
    nonconstant_check = maximum(abs.(X[:, end, :] .- X[:, 1, :])) > 1e-12
    status = all((shape_check, finite_check, full_state_check, clean_noise_check, split_check, window_check, nonconstant_check)) ? "pass" : "fail"
    return Dict(
        "shape_check" => shape_check,
        "finite_check" => finite_check,
        "full_state_check" => full_state_check,
        "clean_noise_check" => clean_noise_check,
        "split_check" => split_check,
        "window_check" => window_check,
        "nonconstant_check" => nonconstant_check,
        "status" => status,
    )
end

