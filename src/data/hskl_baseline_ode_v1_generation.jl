function ensure_parent_dir(path::AbstractString)
    dir = dirname(path)
    if !isempty(dir)
        mkpath(dir)
    end
    return path
end

function write_text_file(path::AbstractString, text::AbstractString)
    ensure_parent_dir(path)
    open(path, "w") do io
        write(io, text)
    end
    return path
end

function write_json_file(path::AbstractString, object)
    ensure_parent_dir(path)
    open(path, "w") do io
        JSON.print(io, object, 2)
        write(io, "\n")
    end
    return path
end

csv_escape(value) = value isa AbstractString ? string('"', replace(value, "\"" => "\"\""), '"') : string(value)

function write_csv(path::AbstractString, columns::AbstractVector{<:AbstractString}, rows::AbstractVector{<:AbstractDict})
    ensure_parent_dir(path)
    open(path, "w") do io
        println(io, join(columns, ","))
        for row in rows
            println(io, join([csv_escape(get(row, col, "")) for col in columns], ","))
        end
    end
    return path
end

