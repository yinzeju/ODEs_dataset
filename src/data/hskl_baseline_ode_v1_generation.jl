function generate_hskl_baseline_ode_v1(; formal_difficulties::AbstractVector{String} = ["medium"])
    systems = hskl_system_specs()
    profiles = hskl_difficulty_profiles()
    write_static_configs(systems, profiles, formal_difficulties)
    write_spec_documents(systems, profiles)

    objects = Dict{String,Any}[]
    representative = Dict{String,Tuple{Vector{Float64},Matrix{Float64}}}()
    for difficulty in formal_difficulties
        profile = profiles[difficulty]
        for system in systems
            for regime in system.regimes
                object, first_matrix, times = generate_one_release_object(system, regime, difficulty, profile)
                push!(objects, object)
                if !haskey(representative, system.system_id)
                    representative[system.system_id] = (times, first_matrix)
                end
                @printf(
                    "%-32s %-20s %-8s status=%s shape=%s\n",
                    system.system_id,
                    regime["parameter_regime"],
                    difficulty,
                    object["validation"]["status"],
                    string(object["tensor_shape"]),
                )
            end
        end
    end

    table_paths = write_release_tables(systems, profiles, objects)
    plot_paths = Dict{String,String}()
    for (system_id, pair) in representative
        times, X = pair
        plot_paths[string(system_id, "_trajectory_overview")] = plot_time_series(
            project_path("reports", HSKL_BENCHMARK_VERSION, "plots", string("hskl_baseline_ode_v1_", system_id, "_trajectory_overview.png")),
            times,
            X,
            system_id,
        )
        phase_name = size(X, 1) == 3 ? string("hskl_baseline_ode_v1_", system_id, "_3d_phase_portrait.png") :
            size(X, 1) > 3 ? string("hskl_baseline_ode_v1_", system_id, "_coordinate_summary.png") :
            string("hskl_baseline_ode_v1_", system_id, "_phase_portrait.png")
        plot_paths[string(system_id, "_phase")] = plot_phase(
            project_path("reports", HSKL_BENCHMARK_VERSION, "plots", phase_name),
            X,
            system_id,
        )
    end

    counters = failure_counters(objects)
    log_path = write_validation_log(project_path("reports", HSKL_BENCHMARK_VERSION, "logs", "hskl_baseline_ode_v1_validation.log"), objects, counters)
    generation_log = write_validation_log(project_path("reports", HSKL_BENCHMARK_VERSION, "logs", "hskl_baseline_ode_v1_generation.log"), objects, counters)

    generated_files = merge(
        table_paths,
        Dict(
            "validation_log" => log_path,
            "generation_log" => generation_log,
            "plots" => plot_paths,
        ),
    )
    manifest = write_manifest(objects, profiles, systems, generated_files, counters, formal_difficulties)
    report_path = write_release_report(
        project_path("reports", HSKL_BENCHMARK_VERSION, "notebooks", "hskl_baseline_ode_v1_release_report.md"),
        objects,
        counters,
        profiles,
        manifest["generated_files"],
    )
    manifest["generated_files"]["release_report"] = report_path
    write_json_file(project_path("data", "releases", HSKL_BENCHMARK_VERSION, "metadata", "release_manifest.json"), manifest)

    return manifest
end

function print_hskl_release_summary(manifest::AbstractDict)
    objects = manifest["objects"]
    pass_count = count(object -> object["validation"]["status"] == "pass", objects)
    @printf("benchmark_version: %s\n", manifest["benchmark_version"])
    @printf("objects: %d\n", length(objects))
    @printf("passed: %d\n", pass_count)
    @printf("failure_counters: %s\n", string(manifest["failure_counters"]))
    @printf("manifest: %s\n", manifest["generated_files"]["release_manifest"])
    return nothing
end
