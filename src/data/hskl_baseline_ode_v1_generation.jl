function generate_one_release_object(system::HSKLSystemSpec, regime::AbstractDict, difficulty::AbstractString, profile::AbstractDict)
    M = Int(profile["M"])
    roles = trajectory_roles(profile)
    R = length(roles)
    parameter_regime = String(regime["parameter_regime"])
    params = Dict{String,Any}(k => v for (k, v) in regime if k != "parameter_regime")
    rng = MersenneTwister(deterministic_seed(HSKL_BENCHMARK_VERSION, system.system_id, parameter_regime, difficulty))

    trajectory_ids = [
        string(system.system_id, "_", parameter_regime, "_", difficulty, "_traj_", lpad(string(q), 4, "0"))
        for q in 1:R
    ]
    pre_burn = Matrix{Float64}(undef, system.state_dim, R)
    retained = Matrix{Float64}(undef, system.state_dim, R)
    matrices = Matrix{Float64}[]

    for q in 1:R
        x0 = sample_initial_condition(rng, system, params)
        pre_burn[:, q] = x0
        retained[:, q] = advance_state(system, params, x0, Int(round(system.burn_in_time / system.dt)))
        X = generate_state_matrix(system, params, x0, M)
        size(X) == (system.state_dim, M + 1) || throw(ArgumentError("wrong trajectory shape for $(system.system_id)"))
        push!(matrices, X)
    end

    X = trajectory_tensor(matrices)
    Z = copy(X)
    Y = copy(X)
    times = collect(range(0.0; step = system.dt, length = M + 1))
    validation = validate_release_object(X, Z, Y, profile, roles)
    paths = object_paths(system, difficulty, regime)

    payload = Dict(
        "benchmark_version" => HSKL_BENCHMARK_VERSION,
        "system_id" => system.system_id,
        "difficulty_level" => String(difficulty),
        "split_id" => "split_i_initial_condition",
        "parameter_regime" => parameter_regime,
        "observation_mode" => HSKL_OBSERVATION_MODE,
        "noise_level" => HSKL_NOISE_LEVEL,
        "dt" => system.dt,
        "M" => M,
        "times" => times,
        "trajectory_ids" => trajectory_ids,
        "split_roles" => roles,
        "parameter_instance" => params,
        "pre_burn_in_initial_conditions" => pre_burn,
        "retained_initial_conditions" => retained,
        "state_tensor" => X,
        "input_tensor" => Z,
        "target_tensor" => Y,
    )
    save_release_arrays(paths, payload)

    metadata = Dict(
        "benchmark_version" => HSKL_BENCHMARK_VERSION,
        "system_id" => system.system_id,
        "layer" => system.layer,
        "difficulty_level" => String(difficulty),
        "split_id" => "split_i_initial_condition",
        "parameter_regime" => parameter_regime,
        "observation_mode" => HSKL_OBSERVATION_MODE,
        "noise_level" => HSKL_NOISE_LEVEL,
        "state_dim" => system.state_dim,
        "M" => M,
        "R" => R,
        "dt" => system.dt,
        "burn_in_time" => system.burn_in_time,
        "solver_profile" => system.solver_profile,
        "tensor_shape" => collect(size(X)),
        "split_counts" => Dict("train" => count(==("train"), roles), "val" => count(==("val"), roles), "test" => count(==("test"), roles)),
        "window_feasibility" => window_feasibility(profile),
        "validation" => validation,
        "generated_files" => paths,
    )
    write_json_file(paths["object_metadata"], metadata)

    return metadata, first(matrices), times
end

