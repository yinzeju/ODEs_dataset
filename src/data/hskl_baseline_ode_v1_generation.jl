function plot_time_series(path::AbstractString, times::AbstractVector, X::AbstractMatrix, system_id::AbstractString)
    ensure_parent_dir(path)
    coords = 1:min(size(X, 1), 4)
    stride = max(1, length(times) ÷ 600)
    plt = plot(; title = string(system_id, " representative trajectory"), xlabel = "t", ylabel = "state")
    for i in coords
        plot!(plt, times[1:stride:end], X[i, 1:stride:end]; label = string("x", i))
    end
    savefig(plt, path)
    return path
end

function plot_phase(path::AbstractString, X::AbstractMatrix, system_id::AbstractString)
    ensure_parent_dir(path)
    stride = max(1, size(X, 2) ÷ 1200)
    if size(X, 1) == 2
        plt = plot(X[1, 1:stride:end], X[2, 1:stride:end]; title = string(system_id, " phase portrait"), xlabel = "x1", ylabel = "x2", label = false)
    elseif size(X, 1) == 3
        plt = plot(X[1, 1:stride:end], X[2, 1:stride:end], X[3, 1:stride:end]; title = string(system_id, " 3D phase portrait"), xlabel = "x1", ylabel = "x2", zlabel = "x3", label = false)
    else
        plt = heatmap(X[:, 1:stride:end]; title = string(system_id, " coordinate summary"), xlabel = "time index", ylabel = "coordinate")
    end
    savefig(plt, path)
    return path
end

